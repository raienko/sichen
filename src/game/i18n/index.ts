export type GameLanguage = "en" | "uk";
const STRINGS: Record<GameLanguage, Record<StringKey, string>> = { en, uk };

export type Vars = Record<string, string | number | Localized>;

export function translate(
  lang: GameLanguage,
  key: StringKey,
  vars?: Vars,
): string {
  let text: string = STRINGS[lang][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      const shown = typeof value === "object" ? value[lang] : String(value);
      text = text.replace(`{{${name}}}`, shown);
    }
  }
  return text;
}

export function useT() {
  const { locale } = useLocale();
  const lang: GameLanguage = locale === "uk" ? "uk" : "en";
  const t = useCallback(
    (key: StringKey, vars?: Vars) => translate(lang, key, vars),
    [lang],
  );
  const tr = useCallback((text: Localized) => text[lang], [lang]);
  return { t, tr, lang };
}
